// generate-sw.js
// Run after `next build` to produce public/sw.js with the correct
// pre-cache list for the current build's chunk filenames.
//
// Usage: node generate-sw.js
// package.json: "build": "next build && node generate-sw.js"

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

// ─── Collect static assets from the build output ─────────────────────────────

function listDir(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter((f) => {
    const full = path.join(dir, f);
    return fs.statSync(full).isFile();
  });
}

const chunksDir = path.join('.next', 'static', 'chunks');
const mediaDir  = path.join('.next', 'static', 'media');
const staticDir = path.join('.next', 'static');

// All JS + CSS chunks
const chunkFiles = listDir(chunksDir)
  .filter((f) => f.endsWith('.js') || f.endsWith('.css'))
  .map((f) => `/_next/static/chunks/${f}`);

// Self-hosted fonts (woff2)
const fontFiles = listDir(mediaDir)
  .filter((f) => f.endsWith('.woff2') || f.endsWith('.woff'))
  .map((f) => `/_next/static/media/${f}`);

// Build-ID manifest files (e.g. _buildManifest.js, _ssgManifest.js)
const buildIdDirs = fs.readdirSync(staticDir).filter((d) => {
  const full = path.join(staticDir, d);
  return (
    fs.statSync(full).isDirectory() &&
    d !== 'chunks' &&
    d !== 'media'
  );
});
const manifestFiles = buildIdDirs.flatMap((d) =>
  listDir(path.join(staticDir, d))
    .filter((f) => f.endsWith('.js'))
    .map((f) => `/_next/static/${d}/${f}`),
);

// Shell resources always pre-cached
const shellFiles = [
  '/offline.html',
  '/manifest.webmanifest',
  '/icons/apple-touch-icon.png',
  '/icons/icon-192.png',
  '/icons/icon-512.png',
];

const allPrecache = [...shellFiles, ...chunkFiles, ...fontFiles, ...manifestFiles];

// ─── Generate a deploy ID from the build content ─────────────────────────────
// Hash the list of filenames so the SW version changes whenever the build changes.
const deployId = crypto
  .createHash('sha1')
  .update(allPrecache.join('\n'))
  .digest('hex')
  .slice(0, 12);

console.log(`[generate-sw] Deploy ID: ${deployId}`);
console.log(`[generate-sw] Pre-caching ${allPrecache.length} assets`);
console.log(`  ${chunkFiles.length} JS/CSS chunks`);
console.log(`  ${fontFiles.length} font files`);
console.log(`  ${manifestFiles.length} manifest files`);
console.log(`  ${shellFiles.length} shell files`);

// ─── Write the service worker ─────────────────────────────────────────────────

const swContent = `// S2G Service Worker — generated by generate-sw.js
// Deploy ID: ${deployId}
// Generated: ${new Date().toISOString()}
// DO NOT EDIT — regenerated on every build.
//
// Cache architecture:
//   SHELL_CACHE  — pre-cached at install: all JS/CSS chunks + fonts + shell
//   IMAGE_CACHE  — cache-first (LRU-60): /_next/image optimised images
//   NAV_CACHE    — network-first: HTML navigation pages
//
// Never cached: /api/* (except image routes), *.supabase.co, admin, auth

const DEPLOY_ID = '${deployId}';
const SHELL_CACHE = 's2g-shell-' + DEPLOY_ID;
const IMAGE_CACHE = 's2g-images-' + DEPLOY_ID;
const NAV_CACHE   = 's2g-nav-'    + DEPLOY_ID;
const ALL_CACHES  = [SHELL_CACHE, IMAGE_CACHE, NAV_CACHE];

// ─── Pre-cache list (all JS/CSS/font chunks for this build) ──────────────────
const PRECACHE_URLS = ${JSON.stringify(allPrecache, null, 2)};

const IMAGE_CACHE_LIMIT = 80;

// ─── Route classifiers ───────────────────────────────────────────────────────

function isNeverCache(url) {
  const { hostname, pathname } = new URL(url);
  if (hostname.endsWith('.supabase.co')) return true;
  // All /api/ routes are network-only EXCEPT the image-serving endpoints
  // which we handle separately below
  if (pathname.startsWith('/api/')) return true;
  if (pathname.startsWith('/admin')) return true;
  // Next.js RSC data fetches — always dynamic
  if (pathname.startsWith('/_next/data/')) return true;
  return false;
}

// Our own API image routes — safe to cache, serve product photos
function isApiImageRoute(url) {
  const { pathname } = new URL(url);
  return /^\\/api\\/(products|customer-requests)\\/[^/]+\\/image$/.test(pathname);
}

// Next.js image optimiser — this is how ALL next/image components load images
// We cache these because they are the actual URLs the browser requests
function isNextImage(url) {
  return new URL(url).pathname.startsWith('/_next/image');
}

// Static assets already in PRECACHE_URLS — also catch any not pre-cached
function isStaticAsset(url) {
  const { pathname } = new URL(url);
  return pathname.startsWith('/_next/static/');
}

function isNavigationRequest(request) {
  return (
    request.mode === 'navigate' ||
    (request.method === 'GET' &&
      (request.headers.get('accept') || '').includes('text/html'))
  );
}

// ─── Install: pre-cache the entire app shell ──────────────────────────────────
self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(SHELL_CACHE)
      .then((cache) =>
        Promise.all(
          PRECACHE_URLS.map((url) =>
            fetch(url, { cache: 'reload' })
              .then((res) => {
                if (res.ok) return cache.put(url, res);
              })
              .catch(() => {
                // Non-fatal: log but don't block install
                console.warn('[S2G SW] Pre-cache miss:', url);
              }),
          ),
        ),
      )
      .then(() => self.skipWaiting()),
  );
});

// ─── Activate: delete stale caches from previous deploys ─────────────────────
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => !ALL_CACHES.includes(key))
            .map((key) => {
              console.log('[S2G SW] Deleting stale cache:', key);
              return caches.delete(key);
            }),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

// ─── Fetch routing ────────────────────────────────────────────────────────────
self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;
  if (!request.url.startsWith('http')) return;

  // 1. Our own API image routes — cache-first
  if (isApiImageRoute(request.url)) {
    event.respondWith(cacheFirstImage(request, false));
    return;
  }

  // 2. Never-cache routes — pass through to network
  if (isNeverCache(request.url)) return;

  // 3. Next.js image optimiser — cache-first
  //    This is the critical fix: next/image always requests /_next/image?url=...
  //    The SW must cache these responses, not the original image URLs.
  if (isNextImage(request.url)) {
    event.respondWith(cacheFirstImage(request, true));
    return;
  }

  // 4. Static JS/CSS/font chunks — cache-first (should already be pre-cached)
  if (isStaticAsset(request.url)) {
    event.respondWith(cacheFirstStatic(request));
    return;
  }

  // 5. HTML navigation — network-first with offline fallback
  if (isNavigationRequest(request)) {
    event.respondWith(navigationHandler(request));
    return;
  }

  // 6. Everything else — network only
});

// ─── Strategy: cache-first for static chunks ─────────────────────────────────
async function cacheFirstStatic(request) {
  const cache = await caches.open(SHELL_CACHE);
  const cached = await cache.match(request);
  if (cached) return cached;
  // Not in pre-cache (shouldn't happen) — fetch and store
  const response = await fetch(request);
  if (response.ok) cache.put(request, response.clone());
  return response;
}

// ─── Strategy: cache-first for images ────────────────────────────────────────
async function cacheFirstImage(request, isNextImageRequest) {
  const cache = await caches.open(IMAGE_CACHE);

  // For /_next/image requests, use the full URL including query params as key
  // because different sizes/qualities are different cached responses
  const cacheKey = isNextImageRequest
    ? request.url  // full URL with ?url=...&w=...&q=...
    : request;

  const cached = await cache.match(cacheKey);
  if (cached) return cached;

  try {
    const response = await fetch(request);
    if (response.ok && response.status === 200) {
      await trimImageCache(cache, IMAGE_CACHE_LIMIT - 1);
      cache.put(cacheKey, response.clone());
    }
    return response;
  } catch {
    // Offline and not cached — return S2G placeholder
    return placeholderImageResponse();
  }
}

// ─── Strategy: network-first for navigation ──────────────────────────────────
async function navigationHandler(request) {
  const navCache = await caches.open(NAV_CACHE);
  try {
    const response = await fetch(request);
    if (response.ok && response.type === 'basic') {
      navCache.put(request, response.clone());
    }
    return response;
  } catch {
    const cached = await navCache.match(request);
    if (cached) return cached;

    // Serve offline.html from shell cache
    const shellCache = await caches.open(SHELL_CACHE);
    const offline = await shellCache.match('/offline.html');
    if (offline) return offline;

    return new Response(
      '<!DOCTYPE html><html><body style="background:#111;color:#F5F2EC;font-family:sans-serif;display:flex;align-items:center;justify-content:center;min-height:100vh;margin:0;text-align:center"><div><div style="font-size:3rem;font-weight:700;letter-spacing:.14em">S2G</div><p style="margin-top:1rem;opacity:.7">You are offline</p></div></body></html>',
      { status: 503, headers: { 'Content-Type': 'text/html' } },
    );
  }
}

// ─── LRU image cache trimmer ──────────────────────────────────────────────────
async function trimImageCache(cache, maxEntries) {
  const keys = await cache.keys();
  if (keys.length >= maxEntries) {
    const toDelete = keys.slice(0, keys.length - maxEntries + 1);
    await Promise.all(toDelete.map((key) => cache.delete(key)));
  }
}

// ─── S2G placeholder image (1×1 dark PNG) ────────────────────────────────────
function placeholderImageResponse() {
  // 1×1 #171717 PNG
  const b64 = 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNk+M9QDwADhgGAWjR9awAAAABJRU5ErkJggg==';
  const bin = atob(b64);
  const arr = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) arr[i] = bin.charCodeAt(i);
  return new Response(arr, {
    status: 200,
    headers: { 'Content-Type': 'image/png' },
  });
}
`;

fs.writeFileSync(path.join('public', 'sw.js'), swContent, 'utf8');
console.log(`[generate-sw] Written public/sw.js (${fs.statSync('public/sw.js').size} bytes)`);
