/**
 * scripts/generate-sw.js
 *
 * Run after `next build` to write public/sw.js with:
 *  - A deploy-specific cache version derived from the BUILD_ID
 *  - A pre-cache list of every JS/CSS chunk + font from this build
 *  - Correct handling of /_next/image (cache, not bypass)
 *  - Network-only for Supabase + all /api/ except image routes
 *  - Offline fallback to /offline.html
 *
 * Usage:  node scripts/generate-sw.js
 * Hook:   "build": "next build && node scripts/generate-sw.js"
 */

'use strict';

const fs   = require('fs');
const path = require('path');

// ─── 1. Read build artefacts ──────────────────────────────────────────────────

const nextDir   = path.resolve('.next');
const staticDir = path.join(nextDir, 'static');
const publicDir = path.resolve('public');

if (!fs.existsSync(nextDir)) {
  console.error('[generate-sw] ERROR: .next directory not found. Run `next build` first.');
  process.exit(1);
}

// Build ID is the canonical version token Next.js already produces
const buildId = fs.readFileSync(path.join(nextDir, 'BUILD_ID'), 'utf8').trim();

function safeReadDir(dir) {
  try {
    return fs.readdirSync(dir).filter(f => fs.statSync(path.join(dir, f)).isFile());
  } catch {
    return [];
  }
}

function safeReadSubDirs(dir) {
  try {
    return fs.readdirSync(dir).filter(f => fs.statSync(path.join(dir, f)).isDirectory());
  } catch {
    return [];
  }
}

// JS + CSS chunks
const chunkUrls = safeReadDir(path.join(staticDir, 'chunks'))
  .filter(f => f.endsWith('.js') || f.endsWith('.css'))
  .map(f => `/_next/static/chunks/${f}`);

// Self-hosted fonts (next/font writes woff2 here)
const fontUrls = safeReadDir(path.join(staticDir, 'media'))
  .filter(f => f.endsWith('.woff2') || f.endsWith('.woff'))
  .map(f => `/_next/static/media/${f}`);

// Build-ID manifest files (_buildManifest.js, _ssgManifest.js, etc.)
const buildIdSubDirs = safeReadSubDirs(staticDir)
  .filter(d => d !== 'chunks' && d !== 'media');

const manifestUrls = buildIdSubDirs.flatMap(d =>
  safeReadDir(path.join(staticDir, d))
    .filter(f => f.endsWith('.js'))
    .map(f => `/_next/static/${d}/${f}`)
);

// Static shell files that must always be available offline
const shellUrls = [
  '/offline.html',
  '/manifest.webmanifest',
  '/icons/apple-touch-icon.png',
  '/icons/icon-192.png',
  '/icons/icon-512.png',
];

// Verify shell files actually exist (warn, don't abort)
for (const u of shellUrls) {
  const abs = path.join(publicDir, u.replace(/^\//, ''));
  if (!fs.existsSync(abs)) {
    console.warn(`[generate-sw] WARNING: shell file missing from public/: ${u}`);
  }
}

const precacheUrls = [...shellUrls, ...chunkUrls, ...fontUrls, ...manifestUrls];

console.log(`[generate-sw] Build ID  : ${buildId}`);
console.log(`[generate-sw] Pre-cache : ${precacheUrls.length} assets`);
console.log(`              ${chunkUrls.length} JS/CSS chunks`);
console.log(`              ${fontUrls.length} font files`);
console.log(`              ${manifestUrls.length} build-manifest files`);
console.log(`              ${shellUrls.length} shell files`);

// ─── 2. Compose the service worker source ────────────────────────────────────

// Serialise the pre-cache array as a JS literal (safe — only URL strings)
const precacheJson = JSON.stringify(precacheUrls, null, 2);

// The SW source is a plain string — no template-literal nesting issues
const swLines = [
  '// S2G Service Worker',
  '// Generated by scripts/generate-sw.js — DO NOT EDIT BY HAND.',
  '// Regenerated on every `npm run build`.',
  '//',
  '// Cache layout:',
  '//   SHELL  — pre-cached at install: all JS/CSS chunks + fonts + shell files',
  '//   IMAGES — cache-first (LRU-80): /_next/image optimised images + API image routes',
  '//   NAV    — network-first: HTML pages (offline fallback to /offline.html)',
  '//',
  '// Never cached: *.supabase.co, /api/* (except image routes),',
  '//               /admin, /_next/data/*, /favicon.ico, POST/non-GET',
  '',
  "const BUILD_ID    = '" + buildId + "';",
  "const SHELL_CACHE = 's2g-shell-'  + BUILD_ID;",
  "const IMAGE_CACHE = 's2g-images-' + BUILD_ID;",
  "const NAV_CACHE   = 's2g-nav-'    + BUILD_ID;",
  'const ALL_CACHES  = [SHELL_CACHE, IMAGE_CACHE, NAV_CACHE];',
  '',
  'const IMAGE_CACHE_LIMIT = 80;',
  '',
  '// Pre-cache list — every JS/CSS chunk + font for this exact build.',
  '// Chunk filenames are content-hashed so this list changes with every build.',
  'const PRECACHE_URLS = ' + precacheJson + ';',
  '',
  '// ---------------------------------------------------------------------------',
  '// Route classifiers',
  '// ---------------------------------------------------------------------------',
  '',
  'function isNeverCache(url) {',
  '  const { hostname, pathname } = new URL(url);',
  '  // Supabase — auth, database, storage',
  '  if (hostname.endsWith(\'.supabase.co\')) return true;',
  '  // Our API routes (image routes are handled before this check)',
  '  if (pathname.startsWith(\'/api/\')) return true;',
  '  // Admin panel',
  '  if (pathname.startsWith(\'/admin\')) return true;',
  '  // Next.js RSC / data fetches — always dynamic',
  '  if (pathname.startsWith(\'/_next/data/\')) return true;',
  '  // favicon.ico is a dynamic App Router route in Next.js App Router —',
  '  // it cannot be cached by the SW and must always go to the network.',
  '  if (pathname === \'/favicon.ico\') return true;',
  '  return false;',
  '}',
  '',
  '// /api/products/123/image  or  /api/customer-requests/uuid/image',
  'function isApiImageRoute(url) {',
  '  const { pathname } = new URL(url);',
  '  return /^\\/api\\/(products|customer-requests)\\/[^/]+\\/image$/.test(pathname);',
  '}',
  '',
  '// /_next/image?url=...&w=...&q=...',
  '// This is the ACTUAL URL the browser requests for every next/image component.',
  '// Must be cached here — caching the original image URL does nothing.',
  'function isNextImage(url) {',
  '  return new URL(url).pathname.startsWith(\'/_next/image\');',
  '}',
  '',
  'function isStaticAsset(url) {',
  '  return new URL(url).pathname.startsWith(\'/_next/static/\');',
  '}',
  '',
  'function isNavigationRequest(request) {',
  '  return (',
  '    request.mode === \'navigate\' ||',
  '    (request.method === \'GET\' &&',
  '      (request.headers.get(\'accept\') || \'\').includes(\'text/html\'))',
  '  );',
  '}',
  '',
  '// ---------------------------------------------------------------------------',
  '// Install — pre-cache the entire app shell',
  '// ---------------------------------------------------------------------------',
  '',
  'self.addEventListener(\'install\', (event) => {',
  '  event.waitUntil(',
  '    caches.open(SHELL_CACHE).then((cache) =>',
  '      Promise.all(',
  '        PRECACHE_URLS.map((url) =>',
  '          fetch(url, { cache: \'reload\' })',
  '            .then((res) => { if (res.ok) return cache.put(url, res); })',
  '            .catch(() => { console.warn(\'[S2G SW] pre-cache miss:\', url); })',
  '        )',
  '      )',
  '    ).then(() => self.skipWaiting())',
  '  );',
  '});',
  '',
  '// ---------------------------------------------------------------------------',
  '// Activate — delete caches from previous builds',
  '// ---------------------------------------------------------------------------',
  '',
  'self.addEventListener(\'activate\', (event) => {',
  '  event.waitUntil(',
  '    caches.keys()',
  '      .then((keys) =>',
  '        Promise.all(',
  '          keys',
  '            .filter((k) => !ALL_CACHES.includes(k))',
  '            .map((k) => { console.log(\'[S2G SW] deleting stale cache:\', k); return caches.delete(k); })',
  '        )',
  '      )',
  '      .then(() => self.clients.claim())',
  '  );',
  '});',
  '',
  '// ---------------------------------------------------------------------------',
  '// Fetch routing',
  '// ---------------------------------------------------------------------------',
  '',
  'self.addEventListener(\'fetch\', (event) => {',
  '  const { request } = event;',
  '  if (request.method !== \'GET\') return;',
  '  if (!request.url.startsWith(\'http\')) return;',
  '',
  '  // 1. API image routes — cache-first (checked before isNeverCache)',
  '  if (isApiImageRoute(request.url)) {',
  '    event.respondWith(cacheFirstImage(request));',
  '    return;',
  '  }',
  '',
  '  // 2. Never-cache — pass straight to network',
  '  if (isNeverCache(request.url)) return;',
  '',
  '  // 3. /_next/image — cache-first',
  '  //    Critical: next/image NEVER requests the original URL directly.',
  '  //    It always goes through /_next/image?url=...&w=...&q=...',
  '  //    Caching this is what makes product images available offline.',
  '  if (isNextImage(request.url)) {',
  '    event.respondWith(cacheFirstImage(request));',
  '    return;',
  '  }',
  '',
  '  // 4. Static JS/CSS/fonts — cache-first (pre-cached at install)',
  '  if (isStaticAsset(request.url)) {',
  '    event.respondWith(cacheFirstStatic(request));',
  '    return;',
  '  }',
  '',
  '  // 5. HTML navigation — network-first + offline fallback',
  '  if (isNavigationRequest(request)) {',
  '    event.respondWith(navigationHandler(request));',
  '    return;',
  '  }',
  '',
  '  // 6. Everything else — network only',
  '});',
  '',
  '// ---------------------------------------------------------------------------',
  '// Strategies',
  '// ---------------------------------------------------------------------------',
  '',
  'async function cacheFirstStatic(request) {',
  '  const cache  = await caches.open(SHELL_CACHE);',
  '  const cached = await cache.match(request);',
  '  if (cached) return cached;',
  '  const response = await fetch(request);',
  '  if (response.ok) cache.put(request, response.clone());',
  '  return response;',
  '}',
  '',
  'async function cacheFirstImage(request) {',
  '  const cache = await caches.open(IMAGE_CACHE);',
  '  // Use the full URL string as cache key so query params (w, q) are preserved',
  '  const cached = await cache.match(request.url);',
  '  if (cached) return cached;',
  '',
  '  // Mobile miss: the same image may be cached at a different width (w= param).',
  '  // Scan for any cached entry sharing the same source url= so the image still',
  '  // appears on mobile even if only a desktop-width variant was cached.',
  '  if (isNextImage(request.url)) {',
  '    const srcUrl = new URL(request.url).searchParams.get(\'url\');',
  '    if (srcUrl) {',
  '      const keys = await cache.keys();',
  '      for (const key of keys) {',
  '        if (new URL(key.url).searchParams.get(\'url\') === srcUrl) {',
  '          return cache.match(key);',
  '        }',
  '      }',
  '    }',
  '  }',
  '',
  '  try {',
  '    // Use request.url (not the request object) to avoid inheriting the',
  '    // original request mode/credentials which can cause CORS failures',
  '    // for /_next/image requests on mobile viewports.',
  '    const response = await fetch(request.url);',
  '    if (response.ok && response.status === 200) {',
  '      await trimImageCache(cache, IMAGE_CACHE_LIMIT - 1);',
  '      cache.put(request.url, response.clone());',
  '    }',
  '    return response;',
  '  } catch {',
  '    return placeholderImage();',
  '  }',
  '}',
  '',
  'async function navigationHandler(request) {',
  '  const navCache = await caches.open(NAV_CACHE);',
  '  try {',
  '    const response = await fetch(request);',
  '    if (response.ok && response.type === \'basic\') {',
  '      navCache.put(request, response.clone());',
  '    }',
  '    return response;',
  '  } catch {',
  '    const cached = await navCache.match(request);',
  '    if (cached) return cached;',
  '    const shellCache = await caches.open(SHELL_CACHE);',
  '    const offline    = await shellCache.match(\'/offline.html\');',
  '    if (offline) return offline;',
  '    return new Response(',
  '      \'<!DOCTYPE html><html><body style="background:#111111;color:#F5F2EC;font-family:sans-serif;display:flex;align-items:center;justify-content:center;min-height:100vh;margin:0;text-align:center"><div><p style="font-size:3rem;font-weight:700;letter-spacing:.14em">S2G</p><p style="margin-top:1rem;opacity:.7">You are offline</p></div></body></html>\',',
  '      { status: 503, headers: { \'Content-Type\': \'text/html\' } }',
  '    );',
  '  }',
  '}',
  '',
  'async function trimImageCache(cache, maxEntries) {',
  '  const keys = await cache.keys();',
  '  if (keys.length >= maxEntries) {',
  '    const toDelete = keys.slice(0, keys.length - maxEntries + 1);',
  '    await Promise.all(toDelete.map((k) => cache.delete(k)));',
  '  }',
  '}',
  '',
  '// 1x1 dark PNG placeholder — shown when an image is offline and not cached',
  'function placeholderImage() {',
  '  const b64 = \'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNk+M9QDwADhgGAWjR9awAAAABJRU5ErkJggg==\';',
  '  const bin = atob(b64);',
  '  const arr = new Uint8Array(bin.length);',
  '  for (let i = 0; i < bin.length; i++) arr[i] = bin.charCodeAt(i);',
  '  return new Response(arr, { status: 200, headers: { \'Content-Type\': \'image/png\' } });',
  '}',
];

const swSource = swLines.join('\n') + '\n';

// ─── 3. Write public/sw.js ────────────────────────────────────────────────────

const outPath = path.join(publicDir, 'sw.js');
fs.writeFileSync(outPath, swSource, 'utf8');

const size = fs.statSync(outPath).size;
console.log(`[generate-sw] Written ${outPath} (${size} bytes)`);

// ─── 4. Validate the output parses as JS ─────────────────────────────────────

try {
  new Function(swSource); // syntax check (not execution)
  console.log('[generate-sw] Syntax check: OK');
} catch (err) {
  console.error('[generate-sw] SYNTAX ERROR in generated sw.js:', err.message);
  process.exit(1);
}

// ─── 5. Verify every pre-cached URL maps to a real file ──────────────────────

let missing = 0;
for (const url of precacheUrls) {
  let filePath;
  if (url.startsWith('/_next/')) {
    filePath = path.join(nextDir, url.replace('/_next/', ''));
  } else {
    filePath = path.join(publicDir, url.replace(/^\//, ''));
  }
  if (!fs.existsSync(filePath)) {
    console.warn(`[generate-sw] WARNING: pre-cache URL has no matching file: ${url}`);
    missing++;
  }
}

if (missing === 0) {
  console.log(`[generate-sw] Asset verification: all ${precacheUrls.length} URLs verified OK`);
} else {
  console.warn(`[generate-sw] Asset verification: ${missing} missing file(s) — check warnings above`);
}

console.log('[generate-sw] Done.');
